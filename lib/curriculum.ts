export interface Su {
  n: number;              // 1~24
  title: string;
  /** 진단 — "글이 ○○한 건 △△ 때문이 아니다"처럼 흔한 오해를 바로잡는 한 줄 */
  diagnose: string;
  /** 묵당의 가르침 — 원리 */
  teach: string[];
  /** 3단계 방법 — 짧은 명령형 */
  steps: string[];
  /** 예시: 고치기 전 → 고친 뒤, 왜 나아졌나 */
  example: { before: string; after: string; why: string };
  /** ② 고쳐 쓰기 — 내 글에서 고칠 문장을 찾는 신호(정규식). 'first'/'last'는 글의 첫·끝 문장 */
  find?: string;
  fix: { task: string; items: string[] };
  /** ③ 한 편 쓰기 — 점검 질문 3개는 퇴고 때 다시 쓴다 */
  write: { prompt: string; type: string; min: number; checks: string[] };
  /** 사진 글감(선택) — 이미지 생성 지시(영어). 이 수의 기법을 쓰기 좋은 장면 */
  photo?: string;
}

export interface Chapter {
  n: number;              // 1~6
  title: string;
  dim: Dim | '종합';
  intro: Line[];
  sus: Su[];
  boss: {
    id: BossId;
    prompt: string;
    type: string;
    minChars: number;
    maxChars?: number;
    /** 1회차 기준 — 항목 6점(5=평균, 7=드묾) 또는 종합 점수. 회차마다 오른다(lib/game.ts) */
    dimMin?: number;
    scoreMin?: number;
    taunt: string[];
    lose: string;
    win: Line[];
  };
}

